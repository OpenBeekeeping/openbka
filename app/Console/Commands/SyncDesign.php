<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Process;

#[Signature('openbka:sync-design {path=../design : Path to the OpenBeekeeping/design repo}')]
#[Description('Copy the Open Beekeeping design system (tokens, CSS, fonts, logos) into OpenBKA')]
class SyncDesign extends Command
{
    /** @var list<string> */
    protected array $logos = [
        'openbka-lockup-on-dark', 'openbka-lockup-on-light',
        'openbka-mark-on-dark', 'openbka-mark-on-light', 'openbka-icon',
    ];

    public function handle(): int
    {
        $source = rtrim($this->argument('path'), '/');
        $source = str_starts_with($source, '/') ? $source : base_path($source);

        if (! File::exists("{$source}/src/tokens.json")) {
            $this->components->error("Error: no design system found at {$source}.");

            return self::FAILURE;
        }

        $this->copy("{$source}/src/tokens.json", resource_path('design/tokens.json'));
        $this->copy("{$source}/dist/openbeekeeping.css", public_path('design/css/openbeekeeping.css'));

        foreach (File::glob("{$source}/fonts/*.woff2") as $font) {
            $this->copy($font, public_path('design/fonts/'.basename($font)));
        }

        foreach ($this->logos as $logo) {
            $this->copy("{$source}/logos/{$logo}.svg", public_path("design/logos/{$logo}.svg"));
        }

        $version = trim(Process::path($source)->run('git describe --tags --always')->output()) ?: 'unknown';

        File::put(public_path('design/css/theme.css'), $this->themeCss($source, $version));
        File::put(public_path('design/VERSION'), $version.PHP_EOL);

        $this->components->info("Synced design system {$version}.");

        return self::SUCCESS;
    }

    protected function copy(string $from, string $to): void
    {
        File::ensureDirectoryExists(dirname($to));
        File::copy($from, $to);
    }

    /**
     * Filament switches themes with a .dark class on <html>, not data-theme,
     * so each theme's colour tokens are restated against that class.
     */
    protected function themeCss(string $source, string $version): string
    {
        $tokens = json_decode(File::get("{$source}/src/tokens.json"), true)['color']['tokens'];

        $block = fn (string $theme): string => collect($tokens)
            ->map(fn (array $token): string => "\t--{$token['name']}: {$token['value'][$theme]};")
            ->prepend("\tcolor-scheme: {$theme};")
            ->implode("\n");

        return <<<CSS
        /* Generated by `php artisan openbka:sync-design` from the design system ({$version}). Do not edit. */
        :root.dark {
        {$block('dark')}
        }

        :root:not(.dark) {
        {$block('light')}
        }

        CSS;
    }
}
